import 'package:powersync/powersync.dart';

// Tables in the database on the phone. PowerSync keeps them in step with
// Supabase: rows arrive through the sync streams (powersync/sync-config.yaml)
// and local changes are uploaded by SupabaseConnector.
//
// Every table has an implicit text "id". Timestamps are ISO-8601 text; always
// compare them with julianday() in SQL, since the server and the phone format
// them slightly differently. Booleans are 0/1 integers; arrays are JSON text.

const localSchema = Schema([
  Table('families', [Column.text('name')]),
  Table('babies', [
    Column.text('family_id'),
    Column.text('name'),
    Column.text('sex'),
    Column.text('birth_date'),
    Column.integer('birth_weight_g'),
    Column.integer('birth_length_mm'),
    Column.integer('birth_head_mm'),
    Column.text('created_at'),
    Column.text('deleted_at'),
  ]),
  Table('feeds', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('type'),
    Column.text('side'),
    Column.text('started_at'),
    Column.text('ended_at'),
    Column.integer('amount_ml'),
    Column.integer('left_seconds'),
    Column.integer('right_seconds'),
    Column.text('timer_side'),
    Column.text('timer_started_at'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('pumping_sessions', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('side'),
    Column.text('started_at'),
    Column.text('ended_at'),
    Column.integer('amount_ml'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('diapers', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('occurred_at'),
    Column.integer('is_wet'),
    Column.integer('is_dirty'),
    Column.text('stool_color'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('sleeps', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('kind'),
    Column.text('started_at'),
    Column.text('ended_at'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('growth_measurements', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('measured_on'),
    Column.integer('weight_g'),
    Column.integer('length_mm'),
    Column.integer('head_mm'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('medications', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('name'),
    Column.text('prescribed_dose'),
    Column.text('dose_times'),
    Column.integer('as_needed'),
    Column.text('start_date'),
    Column.text('end_date'),
    Column.text('prescribed_by'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('medication_doses', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('medication_id'),
    Column.text('given_at'),
    Column.integer('skipped'),
    Column.text('scheduled_for'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('vaccinations', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('vaccine_code'),
    Column.text('given_on'),
    Column.text('batch_number'),
    Column.text('clinic'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('symptom_logs', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('symptom'),
    Column.text('occurred_at'),
    Column.real('temperature_c'),
    Column.integer('severity'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('milk_stash', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('pumping_session_id'),
    Column.text('pumped_at'),
    Column.integer('amount_ml'),
    Column.text('location'),
    Column.text('frozen_at'),
    Column.text('thawed_at'),
    Column.text('finished_at'),
    Column.text('finished_reason'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('food_tries', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('food_id'),
    Column.text('tried_on'),
    Column.text('opinion'),
    Column.text('reaction'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  Table('milestone_checks', [
    Column.text('family_id'),
    Column.text('baby_id'),
    Column.text('milestone_id'),
    Column.text('achieved_on'),
    Column.text('notes'),
    Column.text('deleted_at'),
  ]),
  // Settings for this phone only (never uploaded); id is the setting name.
  Table.localOnly('app_settings', [Column.text('value')]),
  // Reference data, read-only on the phone.
  Table('vaccine_schedule', [
    Column.text('country_code'),
    Column.text('code'),
    Column.text('name'),
    Column.text('dose_label'),
    Column.integer('due_age_value'),
    Column.text('due_age_unit'),
    Column.integer('sort_order'),
    Column.integer('verified'),
  ]),
]);
